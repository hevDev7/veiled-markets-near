// Writes circomlib's Poseidon constants for t = 3 and t = 6 (2 and 5 inputs) as Montgomery-form BN254 scalars,
// so the contract does not link light-poseidon's tables for every width (1.5 MB of wasm).
import { writeFileSync } from 'node:fs';
import constants from '../node_modules/circomlibjs/src/poseidon_constants.js';

const P = 21888242871839275222246405745257275088548364400416034343698204186575808495617n;
const R = (1n << 256n) % P;
const mont = (x) => (BigInt(x) * R) % P;
const limbs = (x) => {
  const out = [];
  for (let i = 0; i < 4; i++) { out.push(`0x${(x & 0xffffffffffffffffn).toString(16)}`); x >>= 64n; }
  return out;
};
const fr = (x) => `Fr::new_unchecked(BigInt([${limbs(mont(x)).join(', ')}]))`;

let src = `// @generated by near/circuits/scripts/gen-poseidon-rs.mjs from circomlibjs poseidon_constants.js. Do not edit.
use ark_bn254::Fr;
use ark_ff::BigInt;

pub const N_ROUNDS_F: usize = 8;
`;
for (const [t, nRoundsP] of [[3, 57], [6, 60]]) {
  const C = constants.C[t - 2];
  const M = constants.M[t - 2];
  if (C.length !== t * (8 + nRoundsP)) throw new Error(`unexpected C length for t=${t}`);
  src += `pub const N_ROUNDS_P_${t}: usize = ${nRoundsP};\n`;
  src += `pub const C${t}: [Fr; ${C.length}] = [\n${C.map((c) => `    ${fr(c)},`).join('\n')}\n];\n`;
  src += `pub const M${t}: [[Fr; ${t}]; ${t}] = [\n${M.map((row) => `    [${row.map(fr).join(', ')}],`).join('\n')}\n];\n`;
}
writeFileSync(process.argv[2], src);
console.log('wrote', process.argv[2]);
