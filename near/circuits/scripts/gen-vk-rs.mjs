// Writes the Groth16 verifying key as little-endian byte constants for the NEAR contract.
// NEAR's alt_bn128 host functions take field elements as 32-byte little-endian integers,
// G1 as (x, y) and G2 as (x.c0, x.c1, y.c0, y.c1): the order snarkjs uses in its JSON.
import { readFileSync, writeFileSync } from 'node:fs';

const [vkPath, outPath] = process.argv.slice(2);
const vk = JSON.parse(readFileSync(vkPath, 'utf8'));
if (vk.protocol !== 'groth16' || vk.curve !== 'bn128') throw new Error('expected groth16 / bn128');

const le32 = (dec) => {
  let v = BigInt(dec);
  const out = [];
  for (let i = 0; i < 32; i++) { out.push(Number(v & 0xffn)); v >>= 8n; }
  if (v !== 0n) throw new Error('value does not fit 32 bytes');
  return out;
};
const g1 = (p) => [...le32(p[0]), ...le32(p[1])];
const g2 = (p) => [...le32(p[0][0]), ...le32(p[0][1]), ...le32(p[1][0]), ...le32(p[1][1])];
const arr = (bytes) => `[${bytes.join(', ')}]`;

const ic = vk.IC.map((p) => `    ${arr(g1(p))},`).join('\n');
const src = `// @generated by near/circuits/scripts/gen-vk-rs.mjs from verification_key.json. Do not edit.
// Circuit: near/circuits/spend.circom (${vk.nPublic} public inputs).

pub const N_PUBLIC: usize = ${vk.nPublic};
pub const ALPHA_G1: [u8; 64] = ${arr(g1(vk.vk_alpha_1))};
pub const BETA_G2: [u8; 128] = ${arr(g2(vk.vk_beta_2))};
pub const GAMMA_G2: [u8; 128] = ${arr(g2(vk.vk_gamma_2))};
pub const DELTA_G2: [u8; 128] = ${arr(g2(vk.vk_delta_2))};
pub const IC: [[u8; 64]; ${vk.IC.length}] = [
${ic}
];
`;
writeFileSync(outPath, src);
console.log(`wrote ${outPath} (${vk.IC.length} IC points)`);
